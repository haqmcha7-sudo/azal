  var WA_BASE = "https://wa.me/212663313457";
  var STORAGE_KEY = "azal-lang";

  function detectLang() {
    try {
      var saved = localStorage.getItem(STORAGE_KEY);
      if (saved === "ar" || saved === "en") return saved;
    } catch (e) {}
    return (navigator.language || "en").toLowerCase().indexOf("ar") === 0
      ? "ar"
      : "en";
  }

  var currentLang = detectLang();
  var listeners = [];

  function getLang() {
    return currentLang;
  }

  function t(key) {
    return (DICT[currentLang] && DICT[currentLang][key]) || DICT.en[key] || key;
  }

  function formatPrice(amount) {
    return currentLang === "ar" ? amount + " درهم" : amount + " MAD";
  }

  function waLink(product) {
    var name = currentLang === "ar" ? product.name_ar : product.name_en;
    return WA_BASE + "?text=" + encodeURIComponent(t("wa_msg") + ": " + name + " (" + product.size + ")");
  }

  function onLangChange(fn) {
    listeners.push(fn);
  }

  function applyI18n(root) {
    root = root || document;
    var els = root.querySelectorAll("[data-i18n]");
    for (var i = 0; i < els.length; i++) {
      var key = els[i].getAttribute("data-i18n");
      if (key) els[i].textContent = t(key);
    }
  }

  function setLang(lang) {
    if (lang !== "ar" && lang !== "en") return;
    currentLang = lang;
    try {
      localStorage.setItem(STORAGE_KEY, lang);
    } catch (e) {}
    var html = document.documentElement;
    html.lang = lang;
    html.dir = lang === "ar" ? "rtl" : "ltr";
    document.title = t("meta_title");
    var meta = document.querySelector('meta[name="description"]');
    if (meta) meta.setAttribute("content", t("meta_desc"));
    applyI18n();
    var toggle = document.getElementById("langToggle");
    if (toggle) {
      var other = toggle.querySelector(".lang-toggle__other");
      var cur = toggle.querySelector(".lang-toggle__current");
      if (other) other.textContent = t("lang_other");
      if (cur) cur.textContent = lang === "ar" ? "ع" : "EN";
    }
    for (var i = 0; i < listeners.length; i++) listeners[i](lang);
  }

